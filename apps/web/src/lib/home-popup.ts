import type { ReactNode } from "react";

// 홈 팝업 — 뜰 수 있는 안내를 한 판에 담아 좌우로 넘겨 보는 슬라이드.
//
// 홈에 뜰 수 있는 안내는 넷이다 — 전면 무료 이벤트(free-promo, 비회원 전용),
// 개발 중 안내(beta-notice), 복습 유도(review-nudge), 출석 이벤트 광고(attendance-promo). 예전에는 각자 자기 모달을 띄웠고, 조건이 겹치는
// 날에는 먼저 준비된 하나가 자리를 잡고 나머지는 조용히 물러났다. 겹쳐 뜨는 것보다야
// 나았지만 물러난 안내는 그 방문에서 아예 닿지 못했고, 셋이 다 뜰 자격이 있는 날에는
// 사용자가 세 번 방문해야 세 개를 다 보는 셈이었다.
//
// 지금은 뜰 자격이 있는 것들을 한 판에 싣고 좌우로 넘긴다. 판은 언제나 하나라 닫기는
// 한 번이면 되고, 뒤에 뭐가 더 있는지는 점(dot)으로 미리 보인다.
//
// 각 안내가 하는 일은 "이번에 낄 자격이 있는가"를 판단해서 슬라이드 한 장을 내놓는
// 것뿐이다(HomePopupSource.resolve). 띄우고·넘기고·닫는 일은 전부
// components/home-popup-slider.tsx 가 한다.
//
// 규칙 하나가 중요하다: **본 장만 봤다고 기록한다.** 실려 있기만 하고 사용자가 넘겨
// 보지 않은 장은 onShown 이 불리지 않으므로 다음 방문에 그대로 다시 기회를 얻는다.
// 그래서 순서에서 밀린 안내도 결국 앞자리에 온다 — 앞 장이 "오늘 봤다"로 기록되고 나면
// 다음 방문에는 그 다음 장이 첫 장이 되기 때문이다.

export type HomePopupControls = {
  // 판 전체를 닫는다. "알겠어요"·"닫기" 같은 오른쪽(주요) 버튼이 쓴다.
  close: () => void;
  // 이 장만 걷어내고 다음 장으로 넘어간다. 남은 장이 없으면 판이 닫힌다.
  // "다시 보지 않기" 같은 왼쪽 버튼이 쓴다 — 사용자가 거절한 건 이 안내지 판 전체가
  // 아니다. 뒤에 있던 장까지 같이 치우면 그 장은 볼 기회를 잃는다.
  dismiss: () => void;
};

export type HomePopupSlide = {
  id: string;
  // 점(dot)과 화면낭독기가 부르는 이름. "출석체크 이벤트" 처럼 무엇에 대한 장인지.
  title: string;
  // 이 장이 실제로 화면에 보인 순간 한 번 불린다. 여기서 "봤다"를 기록한다.
  onShown?: () => void;
  // 판 안에서 스크롤되는 본문.
  body: (controls: HomePopupControls) => ReactNode;
  // 이 장의 머리가 짙은 색으로 꽉 차 있는지(전면 무료 이벤트의 히어로처럼). 판에
  // 하나뿐인 닫기(X)가 그 위에 얹히므로, 켜져 있으면 X 를 반투명 칩으로 띄운다 —
  // 흰 판 기준의 옅은 회색 아이콘은 짙은 색 위에서 거의 안 보인다.
  darkHeader?: boolean;
  // 판을 한 단계 넓게(sm 이상에서). 기본 폭은 글 읽기 좋은 24rem 인데, 이벤트 광고
  // 처럼 한눈에 들어와야 하는 장은 그 폭에서 작아 보인다.
  wide?: boolean;
  // 이 장이 잘리지 않으려면 판이 지켜야 하는 가로/세로 비율(선택). 비율이 고정된
  // 그림 한 장으로 된 장(출석 광고)이 쓴다 — 세로가 짧은 기기에서 판의 폭을 이
  // 비율만큼 함께 줄여야 그림이 판 밖으로 넘치지 않는다. 글로 된 장은 넘치면
  // 스크롤되면 그만이라 주지 않는다.
  aspect?: number;
  // 본문 아래에 고정되는 버튼 띠(선택). 본문이 길어 스크롤되어도 버튼은 제자리에
  // 남는다 — 화면이 짧을 때 닫을 방법이 화면 밖으로 밀려나면 안 된다.
  // 본문과 상태를 나눠 갖는 버튼(예: 복습 시작의 pending)은 이 자리 대신 body 안에
  // 두면 된다. 짧은 장이라 어차피 스크롤될 일이 없다.
  footer?: (controls: HomePopupControls) => ReactNode;
};

// 자격 판정에 필요한, 서버만 아는 값들.
//   attendanceHref — 출석 광고가 어디로 보낼지(회원=출석 현황 / 비회원=가입).
//   signedIn       — 로그인했는지. 전면 무료 이벤트 광고가 비회원에게만 뜨는 데 쓴다
//                    (이미 로그인한 사람에게는 이벤트가 이미 적용돼 있어서, 누를 것이
//                    없는 광고가 다른 안내를 한 칸 뒤로 밀 뿐이다).
export type HomePopupContext = {
  attendanceHref: string;
  signedIn: boolean;
};

export type HomePopupSource = {
  id: string;
  // 뜰 자격이 있으면 슬라이드 한 장을, 아니면 null. 서버를 봐야 하는 안내(복습 유도)가
  // 있어서 비동기도 허용한다 — 늦게 도착한 장은 이미 열린 판에 끼워 넣는다.
  resolve: (ctx: HomePopupContext) => HomePopupSlide | null | Promise<HomePopupSlide | null>;
};
