// 홈에 뜨는 팝업들의 자리 예약.
//
// 홈에는 지금 세 개가 뜰 수 있다 — 개발 중 안내(beta-notice), 복습 유도(review-nudge),
// 출석 이벤트 광고(attendance-promo). 각자 "방문당 한 번" / "하루 한 번" 같은 자기
// 상한만 들고 있어서, 조건이 겹치는 날에는 셋이 동시에 겹쳐 뜬다. 겹치면 z-index 로
// 순서를 정해봐야 아래 것은 안 읽히고, 사용자는 닫기만 세 번 누른다.
//
// 그래서 한 번 그려진 홈에서는 **하나만** 뜬다. 먼저 뜰 준비가 된 쪽이 자리를 잡고,
// 나머지는 조용히 물러난다 — 물러난 쪽은 "봤다"고 기록하지 않으므로 다음 방문에
// 그대로 다시 기회를 얻는다.
//
// 모듈 스코프 변수라 새로고침하면 풀린다(그때는 다시 하나가 뜬다). 닫았다고 풀어주지
// 않는 것은 의도적이다 — 하나를 닫자마자 다음 팝업이 튀어나오면 겹친 것보다 나쁘다.
let claimed = false;

// 자리를 잡았으면 true. 이미 다른 팝업이 떠 있으면 false 이고, 이때 호출부는
// 아무것도 하지 않고 물러나야 한다(기록도 남기지 말 것).
export function claimHomePopup(): boolean {
  if (claimed) return false;
  claimed = true;
  return true;
}
