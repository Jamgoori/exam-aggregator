// 문항 크롭 이미지를 Storage에 올릴 때 쓰는 공통 옵션. 크롭·배치 크롭·webp 이관·폭
// 백필이 각자 올리는데, 캐시 기간이 갈라지면 어떤 경로로 올라갔느냐에 따라 같은
// 이미지가 다르게 캐시된다.
//
// cacheControl = 브라우저가 이미 받은 이미지를 다시 묻지 않고 쓰는 기간(초).
// Supabase 기본값은 3600(1시간)이라, 복습이 같은 문항을 다시 띄우는 시점(틀린 직후
// 3시간 → 1일 → 3일)마다 매번 새로 받고 있었다. 1일로 두면 그중 앞 두 번을 캐시에서
// 바로 그린다.
//
// 더 늘리지 않는 이유: 크롭을 고쳐 다시 올려도(지면 꼬리말 사고처럼 전수 재크롭을
// 돌린 적이 있다) 이미 그 문항을 본 사람의 브라우저에는 이 기간만큼 옛 이미지가
// 남는다. CDN은 upsert 때 무효화되지만 브라우저 캐시는 밀어낼 방법이 없고, 사용자가
// 새로고침해도 안 바뀐다(강력 새로고침이라야 한다). 늘리는 건 즉시 적용되는데 줄이는
// 건 이미 나간 헤더만큼 기다려야 하므로, 짧게 잡고 필요하면 올리는 방향이 안전하다.
// 30일·1년처럼 길게 가려면 파일명에 내용 해시를 붙여 재크롭 시 경로 자체가 바뀌게
// 해야 한다(그러면 옛 이미지가 남을 수가 없다).
const CACHE_SECONDS = 24 * 60 * 60;

export const QUESTION_IMAGE_UPLOAD_OPTIONS = {
  contentType: "image/webp",
  upsert: true,
  cacheControl: String(CACHE_SECONDS),
};
