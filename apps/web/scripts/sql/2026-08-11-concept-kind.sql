-- 개념 종류: 지식형 / 기능형 (2026-08-11, 2026-08-11-concepts.sql 다음)
--
-- 개념 축이 성립하지 않는 문항이 있다. 국어 비문학·영어 독해는 지문이 재출제되지
-- 않아서, "조선 후기 상업의 발달"을 개념으로 세우면 코퍼스에 문항이 한둘뿐이고
-- 사용자에게도 쓸모가 없다 — 그 지문은 다시 안 나온다.
--
-- 독해는 "묻는 능력"으로 묶는다. 빈칸추론·세부내용 일치·문장삽입은 재출제되고,
-- 표본이 넉넉하고, "빈칸추론이 약합니다"가 사용자에게 말이 된다.
--
-- 과목이 아니라 문항 성격으로 갈린다. 국어에도 지식형이 많고(사동·피동, 음운변동,
-- 한글맞춤법), 영어 어법도 지식형이다. 반대로 영어 어휘는 단어별로 세우면 수천 개가
-- 되니 "문맥 어휘추론" 기능형 하나로 묶는다.
--
-- 두 종류를 구분해야 하는 이유:
--
--  1) 진단 문구가 다르다
--     지식형 — "이 개념을 모릅니다. 개념 학습부터"
--     기능형 — "이 유형에 약합니다. 풀이 전략 문제"
--  2) 건강 검진 기준이 다르다
--     지식형은 한 개념이 과목의 20%를 넘으면 입도가 거친 것이지만,
--     기능형은 그게 정상이다(영어 빈칸추론은 실제로 그 비중이다)
--
-- 단원 이름 문자열로 구분하지 않는다. 코드가 unit = '독해 기능' 같은 비교를 하게
-- 되고, 단원 이름은 사람이 언제든 고치는 값이다.
--
-- 추가만 한다. 기존 행은 전부 knowledge 로 남는다.

alter table concepts
  add column if not exists kind text not null default 'knowledge'
  check (kind in ('knowledge', 'skill'));

create index if not exists concepts_kind_idx on concepts(subject_id, kind);

comment on column concepts.kind is
  'knowledge = 지식형(모르면 틀린다). skill = 기능형(독해·추론 등 묻는 능력). 진단 문구와 검진 기준이 갈린다.';

